const unsigned char *tg_fallback_glyph(uint32_t cp) {
    if(cp>=0xc0&&cp<=0x1e9e) {
        for(size_t k=0;k<sizeof latin_extended/sizeof latin_extended[0];k++)
            if(cp==latin_extended[k].upper||cp==latin_extended[k].lower) return latin_extended[k].rows;
    }
    if(cp>=0x0430&&cp<=0x044f) cp-=32;
    if(cp>=0x0410&&cp<=0x042f) return cyrillic[cp-0x0410];
    if(cp==0x0401||cp==0x0451) return io;
    if(cp==0x0404||cp==0x0454) return uk_ie;
    if(cp==0x0406||cp==0x0456) cp='I';
    if(cp==0x0407||cp==0x0457) return uk_yi;
    if(cp==0x0490||cp==0x0491) return uk_ghe;
    if(cp>='a'&&cp<='z') cp-=32;
    if(cp>='A'&&cp<='Z') return font[2+cp-'A'].rows;
    if(cp>='0'&&cp<='9') return font[28+cp-'0'].rows;
    for(size_t k=0;k<sizeof(font)/sizeof(font[0]);k++)
        if(cp==(unsigned char)font[k].ch) return font[k].rows;
    return font[1].rows;
}
