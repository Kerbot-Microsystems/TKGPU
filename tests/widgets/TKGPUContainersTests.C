    CHECK(CALL(".p","pane",".p.a","-weight","-1")==TG_ERROR);
    CHECK(CALL(".p","insert","0",".p.a","-weight","3","-bad","0")==TG_ERROR);
    CHECK(CALL(".p","panes")==TG_OK&&!strcmp(out,".p.b .p.a .p.c"));
