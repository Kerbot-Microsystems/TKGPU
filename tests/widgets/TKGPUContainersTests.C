    CHECK(cascade_regression()==0);
    CHECK(pane_parity_regression()==0);
    tg_ui *u=tg_ui_create(); CHECK(u); char out[512],script[512];
    CHECK(CALL("ttk::panedwindow",".p","-orient","horizontal")==TG_OK);
